"""
First-pass data quality / sufficiency audit on the cleaned groundwater
long-format table. Produces docs/DATA_AUDIT.md and a couple of sanity-check
figures under reports/figures/. Run after src/data/clean_cgwb_data.py.

This exists to answer, with real numbers rather than assumptions, the
questions the project's own requirements demand: is there enough data,
per well and per region, to support forecasting; where are the coverage
gaps; and does the data show the depletion signal the project is meant to
detect (a sanity check, not the final analysis).
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
PROCESSED_PATH = ROOT / "data" / "processed" / "groundwater_levels_long.csv"
DOCS_PATH = ROOT / "docs" / "DATA_AUDIT.md"
FIG_DIR = ROOT / "reports" / "figures"


def load() -> pd.DataFrame:
    df = pd.read_csv(PROCESSED_PATH, parse_dates=["date"])
    df["year"] = df["date"].dt.year
    return df


def well_coverage_stats(df: pd.DataFrame) -> pd.DataFrame:
    return df.groupby("well_id").agg(
        n_readings=("depth_to_water_m", "size"),
        first_year=("year", "min"),
        last_year=("year", "max"),
        state=("state", "first"),
    )


def state_national_trend(df: pd.DataFrame, min_readings: int = 40) -> pd.DataFrame:
    """Yearly mean depth-to-water, restricted to wells with a long enough
    record that a handful of short-lived wells can't swing the average."""
    cov = well_coverage_stats(df)
    good_wells = cov[cov["n_readings"] >= min_readings].index
    sub = df[df["well_id"].isin(good_wells)]
    return sub.groupby("year")["depth_to_water_m"].agg(["mean", "median", "count"])


def most_declining_districts(df: pd.DataFrame, min_readings: int = 20, top_n: int = 10) -> pd.DataFrame:
    """Simple linear trend (metres/year) per district, restricted to wells
    with a usable record length. Positive slope = water table getting
    deeper = depletion."""
    cov = well_coverage_stats(df)
    good_wells = cov[cov["n_readings"] >= min_readings].index
    sub = df[df["well_id"].isin(good_wells)].copy()
    sub["year_frac"] = sub["date"].dt.year + (sub["date"].dt.month - 1) / 12

    def slope(group: pd.DataFrame) -> float:
        if group["year_frac"].nunique() < 3:
            return float("nan")
        import numpy as np

        x = group["year_frac"].to_numpy()
        y = group["depth_to_water_m"].to_numpy()
        m, _ = np.polyfit(x, y, 1)
        return m

    slopes = sub.groupby(["state", "district"]).apply(slope, include_groups=False)
    n_wells = sub.groupby(["state", "district"])["well_id"].nunique()
    result = pd.DataFrame({"slope_m_per_year": slopes, "n_wells": n_wells}).dropna()
    result = result[result["n_wells"] >= 5]
    return result.sort_values("slope_m_per_year", ascending=False).head(top_n)


def main() -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    df = load()
    cov = well_coverage_stats(df)

    n_wells = df["well_id"].nunique()
    n_states = df["state"].nunique()
    n_districts = df[["state", "district"]].drop_duplicates().shape[0]
    n_readings = len(df)
    wells_ge_20 = (cov["n_readings"] >= 20).sum()
    wells_ge_40 = (cov["n_readings"] >= 40).sum()

    trend = state_national_trend(df)
    declining = most_declining_districts(df)

    # Figure 1: national mean depth-to-water over time (wells with >=40 readings)
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.plot(trend.index, trend["mean"], marker="o")
    ax.set_xlabel("Year")
    ax.set_ylabel("Mean depth to water (m below ground)")
    ax.set_title("National mean groundwater depth, wells with >=40 quarterly readings")
    ax.invert_yaxis()  # deeper water table = worse, show it going "down" visually
    fig.tight_layout()
    fig.savefig(FIG_DIR / "national_mean_depth_trend.png", dpi=150)
    plt.close(fig)

    # Figure 2: readings-per-well histogram (coverage sufficiency)
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.hist(cov["n_readings"], bins=40)
    ax.set_xlabel("Number of quarterly readings per well (of 84 possible)")
    ax.set_ylabel("Number of wells")
    ax.set_title("Per-well record length distribution")
    fig.tight_layout()
    fig.savefig(FIG_DIR / "well_coverage_histogram.png", dpi=150)
    plt.close(fig)

    with DOCS_PATH.open("w") as f:
        f.write("# Data Audit\n\n")
        f.write("Generated by `src/eda/data_audit.py` against the cleaned CGWB dataset. ")
        f.write("Numbers below are computed from the actual data, not estimated.\n\n")
        f.write("## Coverage\n\n")
        f.write(f"- Wells: {n_wells:,}\n")
        f.write(f"- States: {n_states}\n")
        f.write(f"- Districts: {n_districts}\n")
        f.write(f"- Total well-quarter readings: {n_readings:,}\n")
        f.write(f"- Wells with >=20 readings: {wells_ge_20:,} ({100*wells_ge_20/n_wells:.1f}%)\n")
        f.write(f"- Wells with >=40 readings: {wells_ge_40:,} ({100*wells_ge_40/n_wells:.1f}%)\n\n")
        f.write("## National mean depth-to-water trend (wells with >=40 readings)\n\n")
        f.write("| Year | Mean depth (m) | Median depth (m) | # readings |\n|---|---|---|---|\n")
        median_count = trend["count"].median()
        for year, row in trend.iterrows():
            flag = " *(partial year — see note)*" if row["count"] < 0.3 * median_count else ""
            f.write(f"| {year} | {row['mean']:.2f} | {row['median']:.2f} | {int(row['count'])} |{flag}\n")
        f.write(
            "\n*Note: 1996 and 2017 are partial years in the source data (readings start "
            "May 1996 and stop Jan 2017), so their averages are drawn from a much smaller, "
            "non-comparable sample and should be read with caution rather than as real "
            "endpoints of the trend.*\n"
        )
        f.write("\n![National trend](../reports/figures/national_mean_depth_trend.png)\n\n")
        f.write("## Per-well record length\n\n")
        f.write("![Well coverage histogram](../reports/figures/well_coverage_histogram.png)\n\n")
        f.write("## Districts with the steepest declining trend (deepening water table)\n\n")
        f.write("Simple linear fit per district, m/year, restricted to districts with >=5 wells that each have >=20 readings. ")
        f.write("This is a sanity check, not the project's final model.\n\n")
        f.write("| State | District | Slope (m/year) | # wells |\n|---|---|---|---|\n")
        for (state, district), row in declining.iterrows():
            f.write(f"| {state} | {district} | {row['slope_m_per_year']:.3f} | {int(row['n_wells'])} |\n")

    print(f"Wrote {DOCS_PATH}")
    print(trend)
    print(declining)


if __name__ == "__main__":
    main()
